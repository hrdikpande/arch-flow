/**
 * Digest composition (DIG-01 to DIG-08). Deterministic text first, then optional
 * Gemini paragraphs that must pass validation. A failed validation sends the
 * deterministic text and records the reason.
 */

import {
  buildDeterministicDigest,
  DIGEST_MAX_CHARS,
  DigestInput,
  validateAiText,
} from '@arch-flow/domain';
import type { Summariser } from '../gemini';
import type { Recipient } from '../ports';

export type DigestSourceRow = Omit<DigestInput, 'date' | 'dashboardUrl' | 'sentLate'>;

export interface DigestSource {
  gather(recipient: Recipient, date: string, now: Date): Promise<DigestSourceRow & { structured: unknown }>;
}

export interface ComposedDigest {
  text: string;
  deterministicText: string;
  aiText: string | null;
  aiValidated: boolean;
  aiRejectionReason: string | null;
}

export interface ComposeDeps {
  source: DigestSource;
  summariser: Summariser | null;
  appUrl: string;
}

export async function composeDigest(
  deps: ComposeDeps,
  recipient: Recipient,
  date: string,
  now: Date,
  sentLate: boolean,
): Promise<ComposedDigest> {
  const gathered = await deps.source.gather(recipient, date, now);
  const { structured, ...rows } = gathered;
  const deterministic = buildDeterministicDigest({
    ...rows,
    date,
    sentLate,
    dashboardUrl: `${deps.appUrl.replace(/\/$/, '')}/dashboard`,
  });

  if (!deps.summariser) {
    return { text: deterministic.text, deterministicText: deterministic.text, aiText: null, aiValidated: false, aiRejectionReason: 'AI summaries are not configured' };
  }

  let aiText: string;
  try {
    aiText = await deps.summariser.summarise(structured);
  } catch (error) {
    return fallback(deterministic.text, 'AI call failed: ' + (error instanceof Error ? error.message : 'unknown'));
  }

  const check = validateAiText(aiText, structured);
  if (!check.ok) return fallback(deterministic.text, check.reason ?? 'validation failed', aiText);

  const combined = `${deterministic.text}\nSummary generated by Gemini:\n${aiText}`;
  if (combined.length > DIGEST_MAX_CHARS) {
    return fallback(deterministic.text, 'AI text would exceed the digest length limit', aiText);
  }
  return { text: combined, deterministicText: deterministic.text, aiText, aiValidated: true, aiRejectionReason: null };
}

function fallback(deterministicText: string, reason: string, aiText: string | null = null): ComposedDigest {
  return { text: deterministicText, deterministicText, aiText, aiValidated: false, aiRejectionReason: reason };
}
